# Operator Precedence and Associativity in Python

# Precedence: Determines the order of operations in expressions
# Associativity: Determines the order of operations when operators have the same precedence

# Precedence Order (from highest to lowest)
# 1. Parentheses ()
# 2. Exponentiation **
# 3. Unary operators (+, -)
# 4. Multiplication (*), Division (/), Floor Division (//), Modulus (%)
# 5. Addition (+), Subtraction (-)
# 6. Bitwise Shifts (<<, >>)
# 7. Bitwise AND (&)
# 8. Bitwise XOR (^)
# 9. Bitwise OR (|)
# 10. Comparison Operators (<, >, <=, >=, ==, !=)
# 11. Identity Operators (is, is not)
# 12. Membership Operators (in, not in)
# 13. Logical NOT (not)
# 14. Logical AND (and)
# 15. Logical OR (or)

# Associativity
# Most operators are left-to-right associative
# Exponentiation is right-to-left associative
